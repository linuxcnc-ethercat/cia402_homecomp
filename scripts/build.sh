#!/bin/bash
set -e
unset CDPATH

ROOT=$(cd -- "$(dirname -- "$0")/.." && pwd)
LINUXCNC_SRC=${LINUXCNC_SRC:-$ROOT/../linuxcnc}
LINUXCNC_ETHERCAT_SRC=${LINUXCNC_ETHERCAT_SRC:-$ROOT/../linuxcnc-ethercat}
BUILD_DIR="$ROOT/build"
HOMING_DIR="$LINUXCNC_SRC/src/emc/motion"

if [ ! -f "$HOMING_DIR/homing.c" ]; then
    echo "LINUXCNC_SRC does not contain src/emc/motion/homing.c" >&2
    exit 1
fi
if [ ! -f "$LINUXCNC_SRC/scripts/rip-environment" ]; then
    echo "Build LinuxCNC as a run-in-place tree first" >&2
    exit 1
fi

mkdir -p "$BUILD_DIR"
cp "$ROOT/cia402_homecomp.comp" "$ROOT/cia402_homecomp.h" "$BUILD_DIR/"
cp "$LINUXCNC_ETHERCAT_SRC/src/lcec_hal_compat.h" "$BUILD_DIR/"
cp "$LINUXCNC_ETHERCAT_SRC/src/cia402.c" "$BUILD_DIR/"
cp "$ROOT/tests/sim/cia402_drive.comp" "$BUILD_DIR/"

{
    echo '/* Generated by scripts/build.sh. */'
    echo "#define HOMING_BASE $HOMING_DIR/homing.c"
    if grep -q 'double home_search_dist' "$HOMING_DIR/homing.h"; then
        echo '#define CIA402_HOMING_HAS_DISTANCES 1'
    fi
} > "$BUILD_DIR/homing_config.h"

. "$LINUXCNC_SRC/scripts/rip-environment"
halcompile --install "$BUILD_DIR/cia402_homecomp.comp"
halcompile --install "$BUILD_DIR/cia402_drive.comp"

cat > "$BUILD_DIR/cia402.mk" <<'EOF'
include $(MODINC)
cia402.so: cia402.o
	$(CC) -shared -Bsymbolic $(RTLDFLAGS) -o $@ cia402.o -lm
EOF
make -C "$BUILD_DIR" -f cia402.mk cia402.so \
    MODINC="$LINUXCNC_SRC/src/Makefile.modinc"
cp "$BUILD_DIR/cia402.so" "$LINUXCNC_SRC/rtlib/cia402.so"

echo "Installed cia402_homecomp, cia402_drive, and cia402 in $LINUXCNC_SRC/rtlib"
